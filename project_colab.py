def overlay_gradcam(original_pil, model, last_conv_layer_name, size=224):
    """Runs inference + Grad-CAM on one PIL image."""
    img_array = keras.utils.img_to_array(original_pil.resize((size, size)))
    img_batch  = np.expand_dims(img_array, axis=0)
    pred_prob  = float(model.predict(img_batch, verbose=0)[0][0])
    heatmap    = make_gradcam_heatmap(img_batch, model, last_conv_layer_name)
    heatmap_col = cv2.applyColorMap(np.uint8(255 * heatmap), cv2.COLORMAP_JET)
    original_np = np.array(original_pil.resize((size, size))) / 255.0
    heatmap_r   = np.float32(cv2.resize(heatmap_col, (size, size))) / 255.0
    superimposed = np.clip(heatmap_r * 0.4 + original_np, 0, 1)
    return original_np, superimposed, pred_prob

def collect_errors(model, dataset_dir, true_label, last_conv_layer_name, max_samples=5):
    """Walk a folder, return up to 5 misclassified images with their Grad-CAMs."""
    errors = []
    for filename in sorted(os.listdir(dataset_dir)):
        if len(errors) >= max_samples: break
        try: img = Image.open(os.path.join(dataset_dir, filename)).convert('RGB')
        except: continue
        orig, sup, prob = overlay_gradcam(img, model, last_conv_layer_name)
        pred_label = 1 if prob >= 0.5 else 0
        if pred_label != true_label:
            errors.append({'original': orig, 'superimposed': sup,
                           'pred_prob': prob, 'filename': filename})
    return errors

def plot_error_grid(errors, error_type, true_label_name):
    """2 × N grid — row 0: originals, row 1: Grad-CAM overlays."""
    n = len(errors)
    if n == 0: print(f"No {error_type} found."); return
    fig, axes = plt.subplots(2, n, figsize=(4*n, 9))
    fig.suptitle(f"{error_type}  |  True: {true_label_name}", fontsize=15)
    for col, item in enumerate(errors):
        ax_o = axes[0, col] if n>1 else axes[0]
        ax_c = axes[1, col] if n>1 else axes[1]
        ax_o.imshow(item['original']);   ax_o.set_title(item['filename'][:20], fontsize=8); ax_o.axis('off')
        ax_c.imshow(item['superimposed']); ax_c.set_title(f"P(AI)={item['pred_prob']:.3f}", fontsize=8); ax_c.axis('off')
    plt.tight_layout(); plt.show()

